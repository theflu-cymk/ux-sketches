// Builds hits.json for sketch 008 from its audio: the strong hits (kick and snare) of the track, found with a
// dynamic-programming beat tracker (after Ellis, 2007) on an onset envelope, plus which hit starts each phrase.
// Usage: node sketches/008-box-model/tools/beat-map.mjs   (needs ffmpeg on PATH)
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const here = (p) => fileURLToPath(new URL(p, import.meta.url))
const AUDIO = here('../public/pressure-redux.mp3')
const OUT = here('../hits.json')
const SR = 11025
const HOP = 64
const WIN = 256
const fps = SR / HOP
/** The track's half-time feel: strong hits every other beat of its 149.7 BPM grid. */
const TARGET_BPM = 74.4

const pcm = execFileSync('ffmpeg', ['-v', 'error', '-i', AUDIO, '-ac', '1', '-ar', String(SR), '-f', 'f32le', '-'], { maxBuffer: 1 << 30 })
const x = new Float32Array(pcm.buffer, pcm.byteOffset, pcm.byteLength / 4)
const duration = x.length / SR

// Onset envelope: rises in log energy, smoothed and standardised.
const n = Math.floor((x.length - WIN) / HOP)
const raw = new Float32Array(n)
let prev = 0
for (let i = 0; i < n; i++) {
  let e = 0
  for (let j = 0; j < WIN; j++) e += x[i * HOP + j] ** 2
  const l = Math.log(1e-9 + e)
  raw[i] = Math.max(0, l - prev)
  prev = l
}
const env = new Float32Array(n)
for (let i = 2; i < n - 2; i++) env[i] = (raw[i - 2] + 2 * raw[i - 1] + 3 * raw[i] + 2 * raw[i + 1] + raw[i + 2]) / 9
const mean = env.reduce((a, b) => a + b, 0) / n
const sd = Math.sqrt(env.reduce((a, b) => a + (b - mean) ** 2, 0) / n)
for (let i = 0; i < n; i++) env[i] = (env[i] - mean) / sd

// Beat tracking: best path of onsets spaced about one period apart.
const P = (60 / TARGET_BPM) * fps
const score = new Float32Array(n)
const back = new Int32Array(n).fill(-1)
for (let t = 0; t < n; t++) {
  let best = -Infinity
  let arg = -1
  for (let q = Math.max(0, Math.round(t - 2 * P)); q <= t - Math.round(P / 2); q++) {
    const v = score[q] - 400 * Math.log((t - q) / P) ** 2
    if (v > best) (best = v), (arg = q)
  }
  score[t] = env[t] + (arg >= 0 ? Math.max(0, best) : 0)
  back[t] = best > 0 ? arg : -1
}
let t = 0
for (let i = Math.max(0, n - Math.round(2 * P)); i < n; i++) if (score[i] > score[t]) t = i
const hits = []
while (t >= 0) (hits.push(t / fps), (t = back[t]))
hits.reverse()

// Downbeat: the phase of four with the heaviest kick (low band, just after each hit).
let lp = 0
const low = new Float32Array(x.length)
for (let i = 0; i < x.length; i++) (lp += 0.03 * (x[i] - lp)), (low[i] = lp)
const kick = hits.map((h) => {
  let e = 0
  const s = Math.round(h * SR)
  for (let i = s; i < Math.min(x.length, s + 0.06 * SR); i++) e += low[i] ** 2
  return e
})
// Change: how different the low end is in the half-bar after a hit versus the half-bar before it (bass and
// harmony tend to move on the downbeat).
const half = (60 / TARGET_BPM) * 2 * SR
const lowEnergy = (s, e) => {
  let v = 0
  for (let i = Math.max(0, Math.round(s)); i < Math.min(x.length, Math.round(e)); i += 4) v += low[i] ** 2
  return v
}
const change = hits.map((h) => {
  const s = h * SR
  const a = lowEnergy(s - half, s)
  const b = lowEnergy(s, s + half)
  return Math.abs(Math.log((b + 1e-9) / (a + 1e-9)))
})
const norm = (arr) => {
  const m = arr.reduce((p, c) => p + c, 0) / arr.length
  return arr.map((v) => v / m)
}
const kickN = norm(kick)
const changeN = norm(change)
const phaseWeight = [0, 1, 2, 3].map((k) => hits.reduce((sum, _, i) => (i % 4 === k ? sum + kickN[i] + changeN[i] : sum), 0))
const downbeat = phaseWeight.indexOf(Math.max(...phaseWeight))
console.log('downbeat evidence by phase (kick + change):', phaseWeight.map((w) => (w / Math.max(...phaseWeight)).toFixed(3)).join(' '))
const map = {
  source: 'pressure-redux.mp3',
  note: 'Strong hits (kick and snare: the half-time of a 149.7 BPM grid). Phrases of four hits start at index `downbeat`. Generated by tools/beat-map.mjs.',
  duration: +duration.toFixed(3),
  downbeat,
  hits: hits.slice(downbeat).map((h) => +h.toFixed(3)),
}
writeFileSync(OUT, `${JSON.stringify(map)}\n`)
const ibi = map.hits.slice(1).map((h, i) => h - map.hits[i])
const m = ibi.reduce((a, b) => a + b, 0) / ibi.length
console.log(`${map.hits.length} hits, mean ${(60 / m).toFixed(2)} BPM (half-time), downbeat phase ${downbeat}, first ${map.hits[0]}s, duration ${map.duration}s`)
